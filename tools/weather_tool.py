    async def _execute(self, text: str):
        """
        Ожидает в тексте упоминание города (субстрока). Благодаря планировщику
        сюда может прийти и чистое название города (args.city).
        """
        text_l = text.lower()
        coords = None
        display = None

        # Поиск города по субстроке
        for key, (lat, lon, disp) in self.CITY_COORDS.items():
            if key in text_l:
                coords = (lat, lon)
                display = disp
                break

        if not coords:
            raise ValueError("Не удалось определить город")

        lat, lon = coords
        url = (
            "https://api.open-meteo.com/v1/forecast"
            f"?latitude={lat}&longitude={lon}&current_weather=true"
        )

        # Устойчивый сетевой вызов: 2 попытки с короткой паузой
        data = None
        for attempt in range(2):
            try:
                async with httpx.AsyncClient(timeout=10) as client:
                    r = await client.get(url)
                    if r.status_code != 200:
                        raise ValueError(f"Ошибка запроса API: {r.status_code}")
                    data = r.json()
                    break
            except Exception:
                if attempt == 0:
                    await asyncio.sleep(0.5)
        if data is None:
            raise ValueError("Не удалось получить погоду после повторов")

        weather = data.get("current_weather", {})
        if not weather:
            raise ValueError("Ответ API не содержит данных о погоде")

        code = weather.get("weathercode")
        description = self.WEATHER_DESC.get(code, "неизвестно")

        return {
            "city": display or "неизвестный город",
            "temp": weather.get("temperature"),
            "windspeed": weather.get("windspeed"),
            "weathercode": code,
            "description": description,
        }
